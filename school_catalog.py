    if stage == "🏫 ابتدائية": return PRIMARY.get(grade, [])
    if stage == "🏫 متوسطة": return INTERMEDIATE.get(grade, [])
    if stage == "🏫 إعدادية" and branch in PREPARATORY: return PREPARATORY[branch].get(grade, [])
    if vocational:
        if department == "عام":
            shared=list(VOCATIONAL_GENERAL.get(vocational, {}).get(vocational_stage, []))
            seen=set(shared)
            for (b, _d, st), vals in VOCATIONAL_SUBJECTS.items():
                if b==vocational and st==vocational_stage:
                    for value in vals:
                        if value not in seen: shared.append(value); seen.add(value)
            return shared
        key=(vocational, department, vocational_stage)
        if key in VOCATIONAL_SUBJECTS: return VOCATIONAL_SUBJECTS[key]
        return VOCATIONAL_GENERAL.get(vocational, {}).get(vocational_stage, [])
    return []
