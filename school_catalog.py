def is_ministerial_grade(stage: str, grade: str, branch: str = "") -> bool:
    """Return True only for Iraqi grades where ministerial exam material is relevant."""
    if grade == "السادس الابتدائي":
        return True
    if grade == "الثالث المتوسط":
        return True
    if grade in {"السادس العلمي", "السادس الأدبي"}:
        return True
    # For vocational education, ministerial/وزاريات material belongs to the
    # third vocational stage (the sixth vocational year), not stages 1 and 2.
    if branch.startswith("مهني /") and grade == "المرحلة الثالثة":
        return True
    return False

